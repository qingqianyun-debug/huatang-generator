export default async function handler(req, res){
  if(req.method !== "POST"){ res.status(405).json({error:"只支持 POST"}); return; }
  const key = process.env.DEEPSEEK_API_KEY;
  if(!key){ res.status(500).json({error:"服务器还没配置 DEEPSEEK_API_KEY，请到 Vercel 环境变量里添加。"}); return; }

  try{
    const { styleK, phaseId, params, styleConstraint } = req.body || {};
    const phases = PHASES_BY_STYLE[styleK];
    if(!phases){ res.status(400).json({error:"未知风格："+styleK+" | 收到的req.body："+JSON.stringify(req.body)}); return; }
    const phase = phases.find(p=>p.id===phaseId);
    if(!phase){ res.status(400).json({error:"未知阶段："+phaseId+" | 收到的req.body："+JSON.stringify(req.body)}); return; }

    const r = await fetch("https://api.deepseek.com/chat/completions", {
      method: "POST",
      headers: { "Content-Type":"application/json", "Authorization":"Bearer "+key },
      body: JSON.stringify({
        model: "deepseek-chat",
        max_tokens: 1000,
        temperature: 0.85,
        messages: [
          { role:"system", content: buildSystemPrompt(styleK, styleConstraint) },
          { role:"user", content: buildUserPrompt(phase, params||{}) }
        ]
      })
    });
    const data = await r.json();
    if(!r.ok){ res.status(502).json({error:"DeepSeek 接口返回错误", detail:data}); return; }
    const text = (data.choices && data.choices[0] && data.choices[0].message && data.choices[0].message.content) || "";
    res.status(200).json({ text });
  }catch(e){
    res.status(500).json({error:"生成失败："+String(e && e.message || e)});
  }
}

