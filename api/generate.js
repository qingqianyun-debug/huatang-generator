// ---------------- 程序化查重：段内查重 + 段间查重 ----------------
// 用字符二元组（bigram）算相似度，不依赖语义理解，专门抓"几乎是同一句换了几个字"这种重复。
function charBigrams(str){
  const s = str.replace(/[，。！？；：、""''（）()\s\[\]【】\-—]/g, "");
  const set = new Set();
  for(let i=0; i<s.length-1; i++) set.add(s.slice(i, i+2));
  return set;
}
function similarity(a, b){
  const A = charBigrams(a), B = charBigrams(b);
  if(A.size === 0 || B.size === 0) return 0;
  let inter = 0;
  for(const g of A) if(B.has(g)) inter++;
  return inter / Math.min(A.size, B.size); // 用较短一句的长度做分母，能抓住"长句包含了短句"这种包含式重复
}
const DEDUP_THRESHOLD = 0.55; // 相似度超过这个值，判定为重复
const DEDUP_MIN_LEN = 15; // 短于这个字数的句子不参与查重（保护锚点句的合理重复，比如反复出现的价格锚点）

function dedupText(text, priorText){
  let lines = text.split("\n").map(l=>l.trim()).filter(Boolean);

  // 段内查重：同一段里，后出现的相似句删掉，保留第一次出现的
  const kept = [];
  for(const line of lines){
    const plain = line.replace(/^\[锚\]\s*/, "");
    if(plain.length < DEDUP_MIN_LEN){ kept.push(line); continue; }
    const isDup = kept.some(k => {
      const kp = k.replace(/^\[锚\]\s*/, "");
      return kp.length >= DEDUP_MIN_LEN && similarity(plain, kp) > DEDUP_THRESHOLD;
    });
    if(!isDup) kept.push(line);
  }
  lines = kept;

  // 段间查重：跟前面已经生成的内容比，撞了就删
  if(priorText && priorText.trim()){
    const priorSentences = priorText.split(/[\n。！？]/).map(s=>s.trim()).filter(s=>s.length >= DEDUP_MIN_LEN);
    lines = lines.filter(line => {
      const plain = line.replace(/^\[锚\]\s*/, "");
      if(plain.length < DEDUP_MIN_LEN) return true;
      return !priorSentences.some(p => similarity(plain, p) > DEDUP_THRESHOLD);
    });
  }

  return lines.join("\n");
}

function stripMetaCommentary(text){
  const metaPatterns = [
    /记住了/, /^那我现在/, /现在开始写/, /现在我来写/, /我来写这一段/, /下面是.{0,10}阶段/,
    /这一阶段的话术/, /这条红线/, /【.{1,20}】.{0,10}阶段/, /^明白[了，]/, /^好的[，,]/,
    /^这段话?说的是.{0,20}不是.{0,20}的事/, /^这[一段句]+(讲|说)的是.{0,20}不是/,
    /你先告诉我.{0,15}(年级|几年级).{0,20}我.{0,10}(直接|再|就).{0,10}(说|讲)/,
    /你可以先告诉我.{0,30}但我不等/, /我先把两条线都讲完/, /我不等.{0,10}我先把/
  ];
  return text.split("\n").filter(line => {
    const t = line.trim();
    if(!t) return false;
    return !metaPatterns.some(re => re.test(t));
  }).join("\n");
}

export default async function handler(req, res){
  if(req.method !== "POST"){ res.status(405).json({error:"只支持 POST"}); return; }
  const key = process.env.ANTHROPIC_API_KEY;
  if(!key){ res.status(500).json({error:"服务器还没配置 ANTHROPIC_API_KEY，请到 Vercel 环境变量里添加。"}); return; }

  try{
    const { styleK, phaseId, params, styleConstraint, priorText } = req.body || {};
    const phases = PHASES_BY_STYLE[styleK];
    if(!phases){ res.status(400).json({error:"未知风格："+styleK+" | 收到的req.body："+JSON.stringify(req.body)}); return; }
    const phase = phases.find(p=>p.id===phaseId);
    if(!phase){ res.status(400).json({error:"未知阶段："+phaseId+" | 收到的req.body："+JSON.stringify(req.body)}); return; }

    const r = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-api-key": key,
        "anthropic-version": "2023-06-01"
      },
      body: JSON.stringify({
        model: "claude-sonnet-4-6",
        max_tokens: 1500,
        temperature: 0.85,
        system: buildSystemPrompt(styleK, styleConstraint),
        messages: [
          { role:"user", content: buildUserPrompt(phase, params||{}, priorText, styleK) }
        ]
      })
    });
    const data = await r.json();
    if(!r.ok){ res.status(502).json({error:"Claude 接口返回错误", detail:data}); return; }
    const rawText = (data.content || []).map(b => b.type === "text" ? b.text : "").join("\n");
    const cleaned = stripMetaCommentary(rawText);
    const text = dedupText(cleaned, priorText);
    res.status(200).json({ text });
  }catch(e){
    res.status(500).json({error:"生成失败："+String(e && e.message || e)});
  }
}

