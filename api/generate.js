// 把 tc 字符串（"0:00–1:00" / "~90s" / "~3min" 等）解析成秒数，再按"整轮约6分钟"估算这一段该讲多少句。
function phaseDurationSeconds(tc){
  if(!tc) return 36;
  const rangeMatch = tc.match(/(\d+):(\d+).*?(\d+):(\d+)/);
  if(rangeMatch){
    const start = parseInt(rangeMatch[1])*60 + parseInt(rangeMatch[2]);
    const end = parseInt(rangeMatch[3])*60 + parseInt(rangeMatch[4]);
    return Math.max(end - start, 15);
  }
  const minMatch = tc.match(/~?(\d+)\s*min/);
  if(minMatch) return parseInt(minMatch[1]) * 60;
  const secMatch = tc.match(/~?(\d+)\s*s/);
  if(secMatch) return parseInt(secMatch[1]);
  return 36;
}
function targetSentenceCount(tc){
  const seconds = phaseDurationSeconds(tc);
  // 正常直播口语语速，大约每句话（含停顿）8秒左右
  return Math.max(3, Math.round(seconds / 8));
}

